// Regenerates ../../../DATA_LICENSE.md from articles.json. Usage: node db/seed/build-license.js
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ARTICLES = new URL('./articles.json', import.meta.url);
const OUT = fileURLToPath(new URL('../../../DATA_LICENSE.md', import.meta.url));
const esc = (text) => text.replaceAll('|', '\\|').replaceAll('[', '\\[').replaceAll(']', '\\]');

const articles = JSON.parse(await readFile(ARTICLES, 'utf8'));
const rows = articles
  .map((a) => `| [${esc(a.title)}](${a.sourceUrl}) | ${esc(a.author)} | ${a.publishedAt.slice(0, 10)} |`)
  .join('\n');

await writeFile(
  OUT,
  `# Data license

The ${articles.length} seeded articles in \`backend/db/seed/articles.json\` are taken from
[English Wikinews](https://en.wikinews.org) and are licensed under
[**Creative Commons Attribution 4.0 International (CC BY 4.0)**](https://creativecommons.org/licenses/by/4.0/).

- License verified on 2026-10-31 from the live site (\`action=query&meta=siteinfo&siprop=rightsinfo\` returns
  "Creative Commons Attribution 4.0", \`https://creativecommons.org/licenses/by/4.0/\`).
- Wikinews has announced it is closing; the articles stay readable and the license is unchanged.
- Changes made: wiki markup and the trailing "Sources" / "Related news" sections were removed (plain text via the
  MediaWiki \`extracts\` API). Titles, text and dates are otherwise unmodified. Tags are the articles' own
  Wikinews categories; summaries, slugs and \`views_count\` are generated by \`backend/db/seed/seed.js\`
  (the view counts are synthetic).
- Author = the Wikinews user who created the page (first revision); date = that revision's timestamp. Articles may
  have had further contributors; see each page's history.
- No images are included.

The portal code itself is not covered by this license. The demo accounts created by the seed are for local
development only.

## Articles

| Article (source URL) | Author (Wikinews user) | Date |
|---|---|---|
${rows}
`,
);
console.log(`wrote ${OUT}`);
